@requires_node
def test_the_consoles_role_cannot_reach_auth_users(client, tenant):
    """The measurement this slice is built on, kept as a test.

    If this ever starts failing, the reason `api/auth_import.py` exists has
    changed and the decision to keep the auth credential platform-side should be
    revisited rather than the test deleted.
    """
    ref = "auth0001"
    tenant(ref)
    _auth_schema(_tenant_admin_dsn(f"mldb_{ref}"), f"mldb_{ref}")
    _allow_several_statements(ref)

    token = _token(client, ref)
    for statement in (
        "SELECT count(*) FROM auth.users",
        "INSERT INTO auth.users (id, email) VALUES (gen_random_uuid(), 'x@y.z')",
    ):
        answered = client.post(
            f"/v1/projects/{ref}/sql", json={"statement": statement},
            headers={"Authorization": f"Bearer {token}"},
        )
        assert answered.status_code == 400
        assert "permission denied" in answered.json()["detail"]


@requires_node
def test_users_and_their_password_hashes_arrive(client, tenant):
    """The point of migrating auth at all: a user signs in with the password
    they already had, rather than discovering at cutover that they must reset."""
    ref = "auth0002"
    tenant(ref)
    _auth_schema(_tenant_admin_dsn(f"mldb_{ref}"), f"mldb_{ref}")

    user_id = str(uuid.uuid4())
    bcrypt_hash = "$2a$10$N9qo8uLOickgx2ZMRZoMyeIjZAgcfl7p92ldGxad68LJZdL17lhWy"  # noqa: S105
    payload = {
        "users": [{
            "id": user_id, "aud": "authenticated", "role": "authenticated",
            "email": "person@example.com", "encrypted_password": bcrypt_hash,
            "email_confirmed_at": "2024-01-01T00:00:00+00:00",
            "raw_user_meta_data": {"name": "A Person"},
            "created_at": "2024-01-01T00:00:00+00:00",
        }],
        "identities": [],
    }

    answered = client.post(
        f"/v1/projects/{ref}/auth/import", json=payload,
        headers={"Authorization": f"Bearer {_token(client, ref)}"},
    )
    assert answered.status_code == 200, answered.text
    assert answered.json()["users_inserted"] == 1

    with psycopg.connect(_tenant_admin_dsn(f"mldb_{ref}")) as conn, conn.cursor() as cur:
        cur.execute("SELECT email, encrypted_password, raw_user_meta_data FROM auth.users")
        email, stored_hash, meta = cur.fetchone()
    assert email == "person@example.com"
    assert stored_hash == bcrypt_hash, "the password hash did not survive the import"
    assert meta == {"name": "A Person"}


@requires_node
def test_a_second_import_is_a_no_op_rather_than_a_duplicate_key(client, tenant):
    """A migration retried after a network failure must not fail mid-cutover."""
    ref = "auth0003"
    tenant(ref)
    _auth_schema(_tenant_admin_dsn(f"mldb_{ref}"), f"mldb_{ref}")
    headers = {"Authorization": f"Bearer {_token(client, ref)}"}
    payload = {"users": [{"id": str(uuid.uuid4()), "email": "again@example.com"}]}

    first = client.post(f"/v1/projects/{ref}/auth/import", json=payload, headers=headers)
    second = client.post(f"/v1/projects/{ref}/auth/import", json=payload, headers=headers)

    assert first.json()["users_inserted"] == 1
    assert second.status_code == 200
    assert second.json()["users_inserted"] == 0
    assert second.json()["users_skipped"] == 1


