"""Migrating Auth users (Phase 08 slice 7, ADR-043).

The shape of this slice was decided by one measurement: **the console's role
cannot touch `auth.users`**. The tenant's `auth` schema is owned by
`mldb_<ref>_auth` (bootstrap 007) and the admin role holds only `USAGE` on the
schema, so `SELECT` and `INSERT` are both denied. Everything slices 6b and 6c do
-- compose SQL, send it to `POST /v1/projects/{ref}/sql` -- is unavailable here.

Granting the admin role access was the obvious alternative and was rejected:
it would put every end user's bcrypt hash within reach of anyone with console
access, on every tier, permanently, for a one-off operation. So the credential
stays platform-side behind a route that composes every statement itself.

That makes the tests here mostly about what the route *refuses*: SQL it is
sent, providers it will not carry, and columns nobody allowlisted.
"""

from __future__ import annotations

import uuid

import psycopg
import pytest

from services.control_plane.api import auth_import
from services.migrate import auth as auth_export
from tests.conftest import TEST_CREDENTIAL, requires_db
from tests.test_provisioning import ADMIN_DSN, _tenant_admin_dsn

pytestmark = [requires_db]
requires_node = pytest.mark.skipif(not ADMIN_DSN, reason="MALUDB_NODE_ADMIN_DSN is unset")


def _token(client, ref: str) -> str:
    return client.post(
        "/v1/auth/signin", json={"email": f"{ref}@example.com", "password": TEST_CREDENTIAL}
    ).json()["token"]


def _allow_several_statements(ref: str) -> None:
    """Free resolves one console statement per eight-second window, and a test
    that sends two gets a 429 that looks like the thing under test failing."""
    from services.control_plane import db

    with db.connection() as conn:
        db.execute(
            conn,
            "UPDATE plans SET config_json = %s WHERE id = "
            "  (SELECT plan_id FROM projects WHERE project_ref = %s)",
            (psycopg.types.json.Jsonb({"limits": {"sql_console_concurrent": 20}}), ref),
        )
        conn.commit()


def _auth_schema(dsn: str, database: str) -> None:
    """A GoTrue-shaped auth schema, created the way a real one is.

    `SET ROLE` to the tenant's auth role first, because that is who owns these
    tables in production: bootstrap 007 hands the schema to `mldb_<ref>_auth`
    and GoTrue migrates as that role. Created as the platform superuser instead,
    the import route -- which connects *as* the auth role -- is denied its own
    tables, which is a fixture bug that looks exactly like a permissions bug.
    """
    with psycopg.connect(dsn, autocommit=True) as conn:
        conn.execute(f'SET ROLE "{database}_auth"')
        # No `CREATE SCHEMA`: bootstrap 002 made it and 007 handed it to this
        # role, and `IF NOT EXISTS` still checks CREATE on the database first.
        conn.execute("""
            CREATE TABLE IF NOT EXISTS auth.users (
                id uuid PRIMARY KEY,
                aud varchar(255), role varchar(255), email varchar(255),
                encrypted_password varchar(255),
                email_confirmed_at timestamptz, last_sign_in_at timestamptz,
                raw_app_meta_data jsonb, raw_user_meta_data jsonb,
                created_at timestamptz, updated_at timestamptz,
                phone text, phone_confirmed_at timestamptz,
                is_super_admin boolean, deleted_at timestamptz
            );
            CREATE TABLE IF NOT EXISTS auth.identities (
                id uuid PRIMARY KEY,
                user_id uuid REFERENCES auth.users(id),
                provider text NOT NULL, provider_id text,
                identity_data jsonb,
                last_sign_in_at timestamptz, created_at timestamptz, updated_at timestamptz
            );
        """)


# -- the allowlist, which needs no database --------------------------------


def test_the_columns_that_are_deliberately_not_carried():
    """In-flight secrets belong to the platform they were minted on.

    Carrying `confirmation_token` or `recovery_token` across a cutover would let
    a token Supabase issued be redeemed against MaluDB. A user midway through a
    password reset starts it again, which is the correct outcome.
    """
    for column in (
        "confirmation_token", "recovery_token", "email_change_token_new",
        "email_change_token_current", "reauthentication_token",
    ):
        assert column not in auth_import.USER_COLUMNS
        assert column not in auth_export.USER_COLUMNS

    # Not a customer's to set, and not the source's to carry.
    assert "is_super_admin" not in auth_import.USER_COLUMNS
    # Generated by newer GoTrue, which refuses to be told a value.
    assert "confirmed_at" not in auth_import.USER_COLUMNS
    # Legacy, always zero.
    assert "instance_id" not in auth_import.USER_COLUMNS


def test_only_email_identities_are_accepted():
    """ADR-043. The scanner reports an external identity as a blocker; this is
    the same rule where it cannot be skipped."""
    assert auth_import.ALLOWED_PROVIDERS == frozenset({"email"})


def test_a_column_nobody_allowlisted_is_dropped_rather_than_written():
    """The route decides what may be written, not the caller."""
    kept, dropped = auth_import._rows_for(
        [{"id": "x", "email": "a@b.c", "is_super_admin": True, "banned_until": "3000-01-01"}],
        auth_import.USER_COLUMNS,
        {"id", "email", "is_super_admin", "banned_until"},
    )
    assert kept == [{"id": "x", "email": "a@b.c"}]
    assert dropped == {"is_super_admin", "banned_until"}


def test_a_column_this_platforms_gotrue_lacks_is_named(capsys):  # noqa: ARG001
    """Supabase and this platform pin different GoTrue versions, so a column in
    the source may not exist here. Named rather than silently discarded."""
    kept, dropped = auth_import._rows_for(
        [{"id": "x", "phone": "+100", "email": "a@b.c"}],
        auth_import.USER_COLUMNS,
        {"id", "email"},  # this destination has no `phone`
    )
    assert kept == [{"id": "x", "email": "a@b.c"}]
    assert dropped == {"phone"}


