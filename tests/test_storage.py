@requires_node
@requires_maludb_core
def test_exceeding_the_quota_restricts_and_audits(storage_project, admin_conn):
    """The end-to-end path, driven by setting a quota the project already
    exceeds rather than by writing a gigabyte of rows."""
    project_id, names, passwords = storage_project("st000008")
    with db.connection() as conn:
        db.execute(
            conn,
            "UPDATE plans SET config_json = %s WHERE id = "
            "(SELECT plan_id FROM projects WHERE id = %s)",
            (psycopg.types.json.Jsonb({"limits": {"database_storage_bytes": 1}}), project_id),
        )
        conn.commit()

    def tenant_connect(database):
        return psycopg.connect(_tenant_admin_dsn(database))

    with db.connection() as conn:
        usage = storage.evaluate(
            conn, admin_conn, project_id=project_id, tenant_connect=tenant_connect
        )
        assert usage.state == storage.RESTRICTED
        row = db.one(
            conn, "SELECT storage_state, storage_restricted_at FROM projects WHERE id = %s",
            (project_id,),
        )
        events = db.query(
            conn, "SELECT event_type, detail_json FROM audit_events WHERE project_id = %s",
            (project_id,),
        )

    assert row["storage_state"] == storage.RESTRICTED
    assert row["storage_restricted_at"] is not None
    assert [e["event_type"] for e in events] == ["storage.restricted"]
    assert events[0]["detail_json"]["quota_bytes"] == 1, "the numbers behind the decision"

    with _as_api_role(names, passwords) as conn, pytest.raises(psycopg.errors.InsufficientPrivilege):
        conn.execute("INSERT INTO public.notes (body) VALUES ('over quota')")


@requires_node
@requires_maludb_core
def test_getting_back_under_releases_the_restriction(storage_project, admin_conn):
    project_id, names, passwords = storage_project("st000009")

    def tenant_connect(database):
        return psycopg.connect(_tenant_admin_dsn(database))

    with db.connection() as conn:
        db.execute(
            conn,
            "UPDATE plans SET config_json = %s WHERE id = "
            "(SELECT plan_id FROM projects WHERE id = %s)",
            (psycopg.types.json.Jsonb({"limits": {"database_storage_bytes": 1}}), project_id),
        )
        conn.commit()
        storage.evaluate(conn, admin_conn, project_id=project_id, tenant_connect=tenant_connect)

        # The customer upgrades, or deletes enough. Either way the next pass
        # must give the writes back.
        db.execute(
            conn,
            "UPDATE plans SET config_json = %s WHERE id = "
            "(SELECT plan_id FROM projects WHERE id = %s)",
            (psycopg.types.json.Jsonb({"limits": {"database_storage_bytes": 10 * 1024 * MB}}),
             project_id),
        )
        conn.commit()
        usage = storage.evaluate(
            conn, admin_conn, project_id=project_id, tenant_connect=tenant_connect
        )
        events = db.query(
            conn, "SELECT event_type FROM audit_events WHERE project_id = %s ORDER BY id",
            (project_id,),
        )

    assert usage.state == storage.OK
    assert [e["event_type"] for e in events] == ["storage.restricted", "storage.released"]
    with _as_api_role(names, passwords) as conn:
        conn.execute("INSERT INTO public.notes (body) VALUES ('writing again')")
        conn.commit()


@requires_node
@requires_maludb_core
def test_re_measuring_an_already_restricted_project_does_not_re_audit(storage_project, admin_conn):
    """A pass that runs every few minutes must not write an audit event every
    few minutes, or the log that explains a restriction becomes the noise that
    hides it."""
    project_id, _, _ = storage_project("st00000a")

    def tenant_connect(database):
        return psycopg.connect(_tenant_admin_dsn(database))

    with db.connection() as conn:
        db.execute(
            conn,
            "UPDATE plans SET config_json = %s WHERE id = "
            "(SELECT plan_id FROM projects WHERE id = %s)",
            (psycopg.types.json.Jsonb({"limits": {"database_storage_bytes": 1}}), project_id),
        )
        conn.commit()
        for _ in range(3):
            storage.evaluate(conn, admin_conn, project_id=project_id, tenant_connect=tenant_connect)
        events = db.query(
            conn, "SELECT event_type FROM audit_events WHERE project_id = %s", (project_id,)
        )
    assert len(events) == 1


