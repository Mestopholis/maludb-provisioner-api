"""Storage accounting and quota enforcement.

The classification is pure and tested as such. The enforcement is not: whether
a revoke actually stops a write is a property of PostgreSQL's privilege system,
and asserting that the right SQL was issued would only test that I can spell
REVOKE. So the restriction tests connect as the tenant's own API role and try to
write.

Restriction is the most customer-visible thing in this phase and the closest to
irreversible-feeling, so these lean on the recovery paths: that a restricted
project can still read, can still delete its way back under, and gets its writes
returned when it does.
"""

from __future__ import annotations

import psycopg
import pytest

from services.control_plane import db, entitlements, storage
from tests.conftest import requires_db
from tests.test_provisioning import (
    ADMIN_DSN,
    _provision,
    _tenant_admin_dsn,
    _tenant_dsn,
    requires_maludb_core,
)

pytestmark = [requires_db]
requires_node = pytest.mark.skipif(not ADMIN_DSN, reason="MALUDB_NODE_ADMIN_DSN is unset")

MB = 1024 * 1024


# -- classification --------------------------------------------------------


def test_a_fresh_project_uses_none_of_its_quota():
    """ADR-015: every tenant carries maludb_core before a customer row.
    Counting it would spend a chunk of a free project's quota at creation, and
    reporting it as negative would be worse."""
    usage = storage.classify(20 * MB, 500 * MB, baseline_bytes=23_639_731)
    assert usage.billable_bytes == 0
    assert usage.state == storage.OK


def test_a_baseline_larger_than_reality_would_hide_all_usage():
    """The bug this module shipped with in its first draft: the constant was set
    to 23 MiB against a real baseline of 23,639,731 bytes (22.5 MiB), so every
    project floored to zero usage and no quota could ever be exceeded. The
    fallback is now deliberately *below* the measured figure."""
    real_baseline = 23_639_731
    assert storage.BASELINE_BYTES < real_baseline, (
        "the fallback baseline must under-subtract: over-subtracting hides usage"
    )
    over_quota = real_baseline + 600 * MB
    assert storage.classify(over_quota, 500 * MB).state == storage.RESTRICTED


def test_the_recorded_baseline_is_preferred_over_the_constant():
    """The figure moves with the extension version, so a project's own recorded
    baseline is the accurate one."""
    generous = storage.classify(100 * MB, 500 * MB, baseline_bytes=90 * MB)
    assert generous.billable_bytes == 10 * MB


def test_the_quota_is_net_of_the_extension_baseline():
    """A project holding exactly its quota of customer data is at 100%, not
    over -- the baseline is not the customer's."""
    usage = storage.classify(storage.BASELINE_BYTES + 500 * MB, 500 * MB)
    assert usage.billable_bytes == 500 * MB
    assert usage.state == storage.RESTRICTED


def test_the_warning_arrives_before_the_restriction():
    """A warning that arrives with the restriction is not a warning."""
    below = storage.classify(storage.BASELINE_BYTES + 399 * MB, 500 * MB)
    at = storage.classify(storage.BASELINE_BYTES + 400 * MB, 500 * MB)
    assert below.state == storage.OK
    assert at.state == storage.WARNING
    assert at.fraction < 1.0


def test_the_raw_measurement_is_preserved_not_just_the_verdict():
    """Storing an adjusted figure would leave nothing able to answer what the
    database actually weighs on disk."""
    usage = storage.classify(123 * MB, 500 * MB)
    assert usage.gross_bytes == 123 * MB


def test_a_project_with_no_quota_is_never_restricted():
    """Failing open here is deliberate: reaching this with no quota means the
    entitlement resolver already misbehaved, and cutting off writes on a
    configuration error is the wrong direction."""
    assert storage.classify(10 * 1024 * MB, 0).state == storage.OK


# -- the restriction, against a real tenant --------------------------------


@pytest.fixture
def storage_project(admin_conn, key_ring, project_factory):
    """A provisioned tenant with a table its API roles can write."""

    def make(ref: str):
        project_id = project_factory(ref)
        with db.connection() as conn:
            node = db.one(
                conn,
                "INSERT INTO nodes (name, hostname, internal_host, node_pool, status) "
                "VALUES ('st-node','st.example','st.internal','shared','active') "
                "ON CONFLICT (name) DO UPDATE SET status='active' RETURNING id",
            )["id"]
            db.execute(conn, "UPDATE projects SET node_id = %s WHERE id = %s", (node, project_id))
            conn.commit()
        names, passwords = _provision(project_id, admin_conn, key_ring, ref)

        with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
            tenant.execute("CREATE TABLE public.notes (id bigint GENERATED BY DEFAULT AS IDENTITY "
                           "PRIMARY KEY, body text)")
            tenant.execute("INSERT INTO public.notes (body) VALUES ('existing')")
            tenant.commit()
        return project_id, names, passwords

    return make


def _as_api_role(names, passwords, role: str = "authenticated"):
    conn = psycopg.connect(_tenant_dsn(names.database, names.authenticator,
                                       passwords["authenticator"]))
    conn.execute(f"SET ROLE {role}")
    return conn


@requires_node
@requires_maludb_core
def test_a_restricted_project_cannot_insert_or_update(storage_project):
    """Asserting the SQL was issued would only test that I can spell REVOKE.
    This asks PostgreSQL."""
    _, names, passwords = storage_project("st000001")
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.restrict(tenant)

    with _as_api_role(names, passwords) as conn:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            conn.execute("INSERT INTO public.notes (body) VALUES ('blocked')")
        conn.rollback()
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            conn.execute("UPDATE public.notes SET body = 'blocked'")
        conn.rollback()


@requires_node
@requires_maludb_core
def test_a_restricted_project_can_still_read(storage_project):
    """Cutting off reads punishes a customer for a condition they need to see
    in order to fix, and stops them exporting their data."""
    _, names, passwords = storage_project("st000002")
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.restrict(tenant)

    with _as_api_role(names, passwords) as conn, conn.cursor() as cur:
        cur.execute("SELECT body FROM public.notes")
        assert [r[0] for r in cur.fetchall()] == ["existing"]


@requires_node
@requires_maludb_core
def test_a_restricted_project_can_delete_its_way_back(storage_project):
    """The recovery path. Revoking DELETE would make the restriction a trap
    only support could unlock."""
    _, names, passwords = storage_project("st000003")
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.restrict(tenant)

    with _as_api_role(names, passwords) as conn:
        conn.execute("DELETE FROM public.notes")
        conn.commit()
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) FROM public.notes")
            assert cur.fetchone()[0] == 0


@requires_node
@requires_maludb_core
def test_a_table_created_while_restricted_is_not_writable(storage_project):
    """The half that bites. Bootstrap 004 grants ALL on future tables, so
    without revoking the default privilege a restricted project could create a
    table and walk straight back out of its restriction."""
    _, names, passwords = storage_project("st000004")
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.restrict(tenant)

    # Created by the platform role, which is the only thing that can create
    # tables in a tenant today: nothing grants mldb_<ref>_admin CREATE on
    # `public`, despite specs/tenant-role-model.md describing it as the role for
    # paid direct SQL. Recorded as a carried-forward gap; using the role that
    # actually creates tables is what makes this test exercise the real path.
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        tenant.execute("CREATE TABLE public.escape (id int)")
        tenant.commit()

    with _as_api_role(names, passwords) as conn, pytest.raises(psycopg.errors.InsufficientPrivilege):
        conn.execute("INSERT INTO public.escape (id) VALUES (1)")


@requires_node
@requires_maludb_core
def test_releasing_restores_writes_including_on_tables_made_while_restricted(storage_project):
    """Restriction has to be fully reversible, or it is a one-way door."""
    _, names, passwords = storage_project("st000005")
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.restrict(tenant)
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        tenant.execute("CREATE TABLE public.made_while_restricted (id int)")
        tenant.commit()
    with psycopg.connect(_tenant_admin_dsn(names.database)) as tenant:
        storage.release(tenant)

    with _as_api_role(names, passwords) as conn:
        conn.execute("INSERT INTO public.notes (body) VALUES ('allowed again')")
        conn.execute("INSERT INTO public.made_while_restricted (id) VALUES (1)")
        conn.commit()


